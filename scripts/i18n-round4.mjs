#!/usr/bin/env node
/**
 * Round-4 i18n supplement: strings the routes build at runtime (status lines,
 * clipboard errors, rendered panels) plus keyed markup whose catalog value was
 * missing.
 *
 * Source of truth lives in scripts/i18n-round4/:
 *   en-keys.json   { js: {tool: {key: en}}, ui: {tool: {key: en}},
 *                    existing: {tool: {section: {key: en}}} }
 *   en-order.json  the English strings, in the order the locale arrays follow
 *   <lang>.json    the translations for that order
 *
 *   node scripts/i18n-round4.mjs && npm run build
 *
 * Writes src/i18n/supplements/round4.js, merged by src/utils/i18n.js under each
 * locale without overriding existing keys. Checked by
 * src/i18n/round4-supplement.test.js.
 */
import fs from "node:fs";

const dir = new URL("./i18n-round4/", import.meta.url);
const read = (name) => JSON.parse(fs.readFileSync(new URL(name, dir), "utf8"));
const LOCALES = ["ko", "ja", "es", "zh-CN", "zh-TW", "fr", "de", "pt", "vi"];

const keys = read("en-keys.json");
const order = read("en-order.json");
const index = new Map(order.map((text, i) => [text, i]));
const lists = Object.fromEntries(LOCALES.map((lang) => [lang, read(`${lang}.json`)]));
for (const lang of LOCALES) {
  if (lists[lang].length !== order.length) {
    throw new Error(`${lang}.json has ${lists[lang].length} entries; en-order.json has ${order.length}`);
  }
}

const entries = [];
for (const section of ["ui", "js"]) {
  for (const [toolId, map] of Object.entries(keys[section] || {})) {
    for (const [key, en] of Object.entries(map)) entries.push({ toolId, section, key, en });
  }
}
for (const [toolId, sections] of Object.entries(keys.existing || {})) {
  for (const [section, map] of Object.entries(sections)) {
    for (const [key, en] of Object.entries(map)) entries.push({ toolId, section, key, en });
  }
}

const out = { en: { tools: {} } };
for (const lang of LOCALES) out[lang] = { tools: {} };
for (const { toolId, section, key, en } of entries) {
  const i = index.get(en);
  if (i === undefined) throw new Error(`no translation slot for ${toolId}.${section}.${key}: ${en}`);
  ((out.en.tools[toolId] ??= {})[section] ??= {})[key] = en;
  for (const lang of LOCALES) {
    const value = lists[lang][i];
    if (typeof value !== "string" || !value.trim()) throw new Error(`${lang}: empty value for ${toolId}.${section}.${key}`);
    ((out[lang].tools[toolId] ??= {})[section] ??= {})[key] = value;
  }
}

const body = `// Generated by scripts/i18n-round4.mjs. Do not edit by hand.\nexport default ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync(new URL("../src/i18n/supplements/round4.js", import.meta.url), body, "utf8");
console.log(`round4 supplement: ${entries.length} keys across ${Object.keys(out.en.tools).length} tools, ${LOCALES.length + 1} locales`);
