#!/usr/bin/env node
/**
 * Round-6 i18n supplement: every English-only string a Korean page still showed
 * after rounds 3-4 (route markup, data-driven tables, the shared page shell and
 * the catalog homepage).
 *
 * Source of truth lives in scripts/i18n-round6/, one JSON file per area, every
 * entry carrying all ten locales:
 *   shell.json  { "<namespace>.<key>": { en, ko, ja, ... } }   non-tool keys
 *   g*.json     { "<toolId>": { "ui"|"js": { "<key>": { en, ko, ... } } } }
 *
 *   node scripts/i18n-round6.mjs && npm run build
 *
 * Writes src/i18n/supplements/round6.js, merged by src/utils/i18n.js under each
 * locale without overriding existing keys. Checked by
 * src/i18n/round6-supplement.test.js.
 */
import fs from "node:fs";

const LANGS = ["en", "ko", "ja", "es", "zh-CN", "zh-TW", "fr", "de", "pt", "vi"];
const dir = new URL("./i18n-round6/", import.meta.url);
const out = Object.fromEntries(LANGS.map((l) => [l, { tools: {} }]));

function check(where, entry) {
  for (const lang of LANGS) {
    if (typeof entry?.[lang] !== "string" || !entry[lang].trim()) {
      throw new Error(`${where}: missing ${lang}`);
    }
  }
}

function setPath(root, path, value) {
  const parts = path.split(".");
  let node = root;
  for (const part of parts.slice(0, -1)) node = node[part] ??= {};
  node[parts.at(-1)] = value;
}

let count = 0;
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const data = JSON.parse(fs.readFileSync(new URL(file, dir), "utf8"));
  if (file === "shell.json") {
    for (const [path, entry] of Object.entries(data)) {
      check(`${file} ${path}`, entry);
      if (path.startsWith("tools.")) throw new Error(`${file}: tool keys belong in a g*.json file`);
      for (const lang of LANGS) setPath(out[lang], path, entry[lang]);
      count++;
    }
    continue;
  }
  for (const [toolId, sections] of Object.entries(data)) {
    for (const [section, map] of Object.entries(sections)) {
      if (section !== "ui" && section !== "js") throw new Error(`${file}: unknown section ${toolId}.${section}`);
      for (const [key, entry] of Object.entries(map)) {
        check(`${file} ${toolId}.${section}.${key}`, entry);
        for (const lang of LANGS) {
          const sec = ((out[lang].tools[toolId] ??= {})[section] ??= {});
          if (sec[key] !== undefined) throw new Error(`duplicate key tools.${toolId}.${section}.${key}`);
          sec[key] = entry[lang];
        }
        count++;
      }
    }
  }
}

const body = `// Generated by scripts/i18n-round6.mjs. Do not edit by hand.\nexport default ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync(new URL("../src/i18n/supplements/round6.js", import.meta.url), body, "utf8");
console.log(`round6 supplement: ${count} keys, ${LANGS.length} locales`);
