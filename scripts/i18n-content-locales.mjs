#!/usr/bin/env node
import fs from "node:fs";

const sourceUrl = new URL("./data/content-locales.json", import.meta.url);
const outputUrl = new URL("../src/ui/generated-content-locales.js", import.meta.url);
const localeSource = JSON.parse(fs.readFileSync(sourceUrl, "utf8"));
const expectedLocales = [
  "ko",
  "ja",
  "es",
  "zh-CN",
  "zh-TW",
  "fr",
  "de",
  "pt",
  "vi",
];
const expectedArticleCount = 10;
const expectedFaqCount = 14;
const legalTextKeys = ["title", "manualUnits", "scriptScope", "accountStatus"];

function validateLegalText(locale, legal) {
  if (
    !legal ||
    typeof legal.responseMessage !== "string" ||
    legalTextKeys.some((key) => typeof legal.adPolicy?.[key] !== "string")
  ) {
    throw new Error(`${locale} has incomplete legal disclosure text`);
  }
}

if (localeSource.sourceLocale !== "en") {
  throw new Error("The authoritative content source locale must remain English");
}
validateLegalText("en", localeSource.englishLegal);
if (
  JSON.stringify(Object.keys(localeSource.locales)) !==
  JSON.stringify(expectedLocales)
) {
  throw new Error("The reviewed locale list or order is invalid");
}
for (const locale of expectedLocales) {
  const { articles, faq, legal } = localeSource.locales[locale];
  validateLegalText(locale, legal);
  if (
    articles.length !== expectedArticleCount ||
    faq.length !== expectedFaqCount
  ) {
    throw new Error(
      `${locale} must contain ${expectedArticleCount} articles and ${expectedFaqCount} FAQ entries`,
    );
  }
  if (new Set(articles.map(({ slug }) => slug)).size !== expectedArticleCount) {
    throw new Error(`${locale} contains duplicate article slugs`);
  }
  if (new Set(faq.map(({ id }) => id)).size !== expectedFaqCount) {
    throw new Error(`${locale} contains duplicate FAQ ids`);
  }
}

const contentCatalog = Object.fromEntries(
  Object.entries(localeSource.locales).map(([locale, { articles, faq }]) => [
    locale,
    { articles, faq },
  ]),
);
const legalContent = Object.fromEntries([
  ["en", localeSource.englishLegal],
  ...Object.entries(localeSource.locales).map(([locale, { legal }]) => [
    locale,
    legal,
  ]),
]);
const output = `// Generated by scripts/i18n-content-locales.mjs. Do not edit directly.\nexport const REVIEWED_CONTENT_LOCALES = Object.freeze(${JSON.stringify(contentCatalog, null, 2)});\nexport const REVIEWED_LEGAL_CONTENT = Object.freeze(${JSON.stringify(legalContent, null, 2)});\n`;
const before = fs.existsSync(outputUrl)
  ? fs.readFileSync(outputUrl, "utf8")
  : "";

if (process.argv.includes("--check")) {
  if (before !== output) throw new Error("Generated reviewed content locales are stale");
  console.log("Reviewed content locales are current");
} else if (before !== output) {
  fs.writeFileSync(outputUrl, output);
  console.log("Generated reviewed content locales");
} else {
  console.log("Reviewed content locales are current");
}
