#!/usr/bin/env node
/**
 * Round-3 i18n supplement: UI strings that shipped in English only.
 *
 * Source of truth lives in scripts/i18n-round3/:
 *   en-keys.json   tool id -> { r3_N: English } (the data-i18n keys wired into routes)
 *   en-order.json  the English strings that need translating, in a fixed order
 *   <lang>.json    the translations for that order, one array per locale
 * Strings in en-keys.json but not in en-order.json are identical in every
 * language (algorithm names, sample bytes, code).
 *
 *   node scripts/i18n-round3.mjs && npm run build
 *
 * Writes src/i18n/supplements/round3.js, which src/utils/i18n.js merges under
 * each locale without overriding existing keys. Parity is enforced by
 * src/i18n/round3-supplement.test.js.
 */
import fs from "node:fs";

const dir = new URL("./i18n-round3/", import.meta.url);
const read = (name) => JSON.parse(fs.readFileSync(new URL(name, dir), "utf8"));
const LOCALES = ["ko", "ja", "es", "zh-CN", "zh-TW", "fr", "de", "pt", "vi"];

const keys = read("en-keys.json");
const order = read("en-order.json");
const index = new Map(order.map((text, i) => [text, i]));

const out = { en: { tools: {} } };
for (const lang of LOCALES) {
  const list = read(`${lang}.json`);
  if (list.length !== order.length) {
    throw new Error(`${lang}.json has ${list.length} entries; en-order.json has ${order.length}`);
  }
  out[lang] = { tools: {}, list };
}

for (const [toolId, ui] of Object.entries(keys)) {
  for (const [key, english] of Object.entries(ui)) {
    (out.en.tools[toolId] ??= { ui: {} }).ui[key] = english;
    const i = index.get(english);
    for (const lang of LOCALES) {
      const value = i === undefined ? english : out[lang].list[i];
      if (typeof value !== "string" || !value.trim()) throw new Error(`${lang}: empty value for ${toolId}.${key}`);
      (out[lang].tools[toolId] ??= { ui: {} }).ui[key] = value;
    }
  }
}
for (const lang of LOCALES) delete out[lang].list;

const body = `// Generated by scripts/i18n-round3.mjs. Do not edit by hand.\nexport default ${JSON.stringify(out, null, 2)};\n`;
fs.mkdirSync(new URL("../src/i18n/supplements/", import.meta.url), { recursive: true });
fs.writeFileSync(new URL("../src/i18n/supplements/round3.js", import.meta.url), body, "utf8");
const total = Object.values(keys).reduce((n, ui) => n + Object.keys(ui).length, 0);
console.log(`round3 supplement: ${total} keys across ${Object.keys(keys).length} tools, ${LOCALES.length + 1} locales`);
